#!/usr/bin/env bash
# cakeml/replay.sh — the CakeML binary from this repository, on a fresh Ubuntu 24.04 x86_64 machine: the toolchain
# (setup-cakeml.sh: Poly/ML 5.9.2, HOL trindemossen-2-v10, CakeML v3671 and its basis, the released cake binary), the
# binary (build-binary.sh), the inputs, and the 52 runs against the kernel's verdicts (run-binary.sh; nonzero exit on
# any disagreement).
# This is cert-machine's hol4/delta3/cakeml/replay.sh with its paths moved to this repository's layout (2026-11-25):
# the checker is read from checker/, the inputs from data/, the cover files are regenerated by export/make-cover.py
# and compared with data/, the battery files by export/make-battery.py from export/battery-parts/. Not yet run in
# this layout (the original ran on a pod on 2026-11-25).
#   bash cakeml/replay.sh <repository root>    [PREFIX=/root/cm]  [CAKEML_SETUP_DONE=1: setup-cakeml.sh already ran]
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$1" && pwd)"
export PREFIX="${PREFIX:-/root/cm}"
[ "${CAKEML_SETUP_DONE:-0}" = 1 ] || bash "$HERE/setup-cakeml.sh"
bash "$HERE/build-binary.sh" "$HERE" "$REPO/checker"
IN="$PREFIX/inputs"; S="$PREFIX/sources"; rm -rf "$IN" "$S"
mkdir -p "$IN/day2" "$IN/cakeml/d3" "$IN/battery" "$S/cover/day2" "$S/battery"
cp "$REPO"/data/slabA.d3 "$REPO"/data/slabB.d3 "$REPO"/data/slabC.d3 "$REPO"/data/slabD.d3 "$REPO"/data/slabC_red_*.d3 "$IN/"
cp "$REPO"/data/inner.d3 "$REPO"/data/inner_red_*.d3 "$IN/day2/"
cp "$REPO"/data/slabA.d3 "$REPO"/data/slabB.d3 "$REPO"/data/slabC.d3 "$REPO"/data/slabD.d3 "$S/cover/"
cp "$REPO"/data/inner.d3 "$S/cover/day2/"
python3 -I "$REPO/export/make-cover.py" "$S/cover" "$IN/cakeml/d3"
for f in cover cover_red_gap cover_red_noinner cover_red_short; do cmp "$IN/cakeml/d3/$f.d3" "$REPO/data/$f.d3"; done
cp "$REPO"/export/battery-parts/* "$S/battery/"
cp "$REPO"/data/slabA.d3 "$REPO"/data/slabB.d3 "$REPO"/data/slabC.d3 "$REPO"/data/slabD.d3 "$REPO"/data/inner.d3 "$S/battery/"
python3 -I "$REPO/export/make-battery.py" "$S/battery" "$IN/battery"
( cd "$IN/battery" && sha256sum r*.d3 ) | diff - "$REPO/data/battery.sha256"
echo "the cover files and the 37 battery files are byte-identical to data/"
sed "s|/root/cm/inputs|$IN|" "$HERE/inputs-pod.tsv" > "$PREFIX/inputs.tsv"
bash "$HERE/run-binary.sh" "$PREFIX/out/delta3" "$PREFIX/inputs.tsv" "$PREFIX/out/runs"
